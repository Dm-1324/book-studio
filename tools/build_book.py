import design  # noqa: E402

FONTS = ROOT / "assets" / "fonts"
pdfmetrics.registerFont(TTFont("Body", str(FONTS / "AtkinsonHyperlegible-Regular.ttf")))
pdfmetrics.registerFont(TTFont("BodyBold", str(FONTS / "AtkinsonHyperlegible-Bold.ttf")))
pdfmetrics.registerFont(TTFont("Display", str(FONTS / "ArchivoBlack-Regular.ttf")))

INSIDE, OUTSIDE, TOP, BOTTOM = 0.75 * inch, 0.6 * inch, 0.5 * inch, 0.5 * inch  # KDP minimum is 0.25 in
INK, GREY = (0, 0, 0), (0.45, 0.45, 0.45)


class Book:
    def __init__(self, path, cfg):
        self.cfg = cfg
        self.w, self.h = cfg["trim"][0] * inch, cfg["trim"][1] * inch
        self.c = canvas.Canvas(str(path), pagesize=(self.w, self.h), initialFontName="Body")
        self.c.setTitle(cfg["title"])
        self.c.setAuthor(cfg["author"])
        self.page = 1
        self.numbered = False

    # content box for the current page; odd pages are right-hand pages (gutter on the left)
    @property
    def box(self):
        left = INSIDE if self.page % 2 == 1 else OUTSIDE
        right = OUTSIDE if self.page % 2 == 1 else INSIDE
        return left, BOTTOM, self.w - left - right, self.h - TOP - BOTTOM

    @property
    def framed(self):
        return (self.cfg.get("design") or {}).get("style", "framed") in ("framed", "illustrated")

    def next_page(self):
        if self.numbered and self.framed:
            design.footer(self)
        elif self.numbered:
            x, _, cw, _ = self.box
            self.c.setFont("Body", 11)
            self.c.setFillColorRGB(*GREY)
            self.c.drawCentredString(x + cw / 2, BOTTOM * 0.55, str(self.page))
            self.c.setFillColorRGB(*INK)
        self.c.showPage()
        self.page += 1

    def text_block(self, text, x, y, width, font="Body", size=14, leading=None):
        leading = leading or size * 1.45
        self.c.setFont(font, size)
        for para in text.strip().split("\n\n"):
            words, line = para.split(), ""
            for w in words:
                trial = (line + " " + w).strip()
                if pdfmetrics.stringWidth(trial, font, size) > width:
                    self.c.drawString(x, y, line)
                    y -= leading
                    line = w
                else:
                    line = trial
            if line:
                self.c.drawString(x, y, line)
                y -= leading
            y -= leading * 0.6
        return y

    def save(self):
        self.c.save()


