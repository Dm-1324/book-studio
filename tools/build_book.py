"""Build a puzzle book interior PDF for KDP.

usage: python tools/build_book.py books/<slug> [--dry-run]

Reads   book.yaml, content/puzzles.yaml (word search)
Writes  dist/puzzles.json, dist/interior.pdf, dist/build.json (page count etc.)
"""
