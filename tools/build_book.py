def title_page(b):
    cfg = b.cfg
    x, y, cw, ch = b.box
    mid = x + cw / 2
    c = b.c
    c.setFont("Display", 34)
    _centred_lines(c, cfg["title"], mid, y + ch * 0.68, "Display", 34, cw, 42)
    c.setFont("Body", 17)
    _centred_lines(c, cfg["subtitle"], mid, y + ch * 0.5, "Body", 17, cw * 0.85, 24)
    c.setFont("BodyBold", 15)
    c.drawCentredString(mid, y + ch * 0.2, cfg["author"])
    b.next_page()


def copyright_page(b):
    cfg = b.cfg
    x, y, cw, ch = b.box
    lines = [
        f"{cfg['title']}",
        f"Copyright © {cfg['year']} {cfg['author']}. All rights reserved.",
        "No part of this book may be reproduced without written permission,",
        "except for personal use by the owner of this copy.",
        "",
        "Puzzles were generated by computer and checked so that every",
        "puzzle can be solved. Answers are at the back of the book.",
    ]
    b.c.setFont("Body", 10.5)
    b.c.setFillColorRGB(*GREY)
    yy = y + 2.2 * inch
    for line in lines:
        b.c.drawString(x, yy, line)
        yy -= 15
    b.c.setFillColorRGB(*INK)
    b.next_page()


def how_to_page(b):
    x, y, cw, ch = b.box
    b.c.setFont("Display", 26)
    b.c.drawString(x, y + ch - 30, "How to play")
    b.text_block(b.cfg["how_to_play"], x, y + ch - 80, cw, size=16)
    b.next_page()


def section_page(b, heading, sub=""):
    x, y, cw, ch = b.box
    b.c.setFont("Display", 40)
    b.c.drawCentredString(x + cw / 2, y + ch * 0.55, heading)
    if sub:
        b.c.setFont("Body", 16)
        b.c.drawCentredString(x + cw / 2, y + ch * 0.55 - 40, sub)
    b.next_page()


def back_page(b):
    x, y, cw, ch = b.box
    b.c.setFont("Display", 26)
    b.c.drawString(x, y + ch - 30, "Thank you")
    yy = b.text_block(b.cfg["back_page"], x, y + ch - 80, cw, size=15)
    series = b.cfg.get("series")
    if series:
        b.c.setFont("BodyBold", 15)
        b.c.drawString(x, yy - 20, f"Also in the {series} series:")
        b.c.setFont("Body", 15)
        yy -= 48
        for other in b.cfg.get("also_in_series", []):
            b.c.drawString(x + 14, yy, "•  " + other)
            yy -= 24
    b.next_page()


def balanced_lines(text, font, size, width):
    """Fewest lines that fit, then the most even line lengths (no lonely last word)."""
    words = text.split()
    sw = lambda s: pdfmetrics.stringWidth(s, font, size)  # noqa: E731
    for n in range(1, len(words) + 1):
        best = None
        def split(ws, k):
            if k == 1:
                yield [" ".join(ws)]
                return
            for i in range(1, len(ws) - k + 2):
                for rest in split(ws[i:], k - 1):
                    yield [" ".join(ws[:i])] + rest
        for cand in split(words, n):
            widths = [sw(l) for l in cand]
            if max(widths) <= width and (best is None or max(widths) < best[0]):
                best = (max(widths), cand)
        if best:
            return best[1]
    return words


def _centred_lines(c, text, mid, y, font, size, width, leading):
    lines = balanced_lines(text, font, size, width)
    c.setFont(font, size)
    for i, ln in enumerate(lines):
        c.drawCentredString(mid, y - i * leading, ln)


# ---------- word search ----------

def draw_wordsearch_grid(c, ws, x0, y_top, cell, font_size, answers=False, colors=None, frame_col=None, ink=INK):
    grid = ws["grid"]
    n = len(grid)
    if answers:
        c.setLineWidth(cell * (0.09 if colors else 0.06))
        c.setStrokeColorRGB(0.35, 0.35, 0.35)
        for k, p in enumerate(ws["placements"].values()):
            if colors:
                c.setStrokeColorRGB(*colors[k % len(colors)])
            dr, dc = DIRS[p["dir"]]
            r0, c0 = p["row"], p["col"]
            r1, c1 = r0 + dr * (p["len"] - 1), c0 + dc * (p["len"] - 1)
            ax, ay = x0 + (c0 + 0.5) * cell, y_top - (r0 + 0.5) * cell
            bx, by = x0 + (c1 + 0.5) * cell, y_top - (r1 + 0.5) * cell
            _capsule(c, ax, ay, bx, by, cell * 0.42)
        c.setStrokeColorRGB(*INK)
    c.setLineWidth(2.0 if frame_col else 1.2)
    c.setStrokeColorRGB(*(frame_col or INK))
    c.roundRect(x0 - cell * 0.25, y_top - n * cell - cell * 0.25, n * cell + cell * 0.5, n * cell + cell * 0.5,
                cell * 0.3, stroke=1, fill=0)
    c.setStrokeColorRGB(*INK)
    c.setFillColorRGB(*ink)
    c.setFont("BodyBold" if not answers else "Body", font_size)
    for r in range(n):
        for col in range(n):
            cx = x0 + (col + 0.5) * cell
            cy = y_top - (r + 0.5) * cell - font_size * 0.35
            c.drawCentredString(cx, cy, grid[r][col])
    c.setFillColorRGB(*INK)


def _capsule(c, ax, ay, bx, by, rad):
    import math
    ang = math.atan2(by - ay, bx - ax)
    length = math.hypot(bx - ax, by - ay)
    c.saveState()
    c.translate(ax, ay)
    c.rotate(math.degrees(ang))
    c.roundRect(-rad, -rad, length + 2 * rad, 2 * rad, rad, stroke=1, fill=0)
    c.restoreState()


def wordsearch_page(b, num, entry, ws):
    cfg = b.cfg
    x, y, cw, ch = b.box
    c = b.c
    c.setFont("BodyBold", 13)
    c.setFillColorRGB(*GREY)
    c.drawString(x, y + ch - 14, f"PUZZLE {num}")
    c.setFillColorRGB(*INK)
    c.setFont("Display", 24)
    c.drawString(x, y + ch - 44, entry["title"])
    n = len(ws["grid"])
    words = sorted(ws["words"], key=str.upper)
    cols = 3
    rows = (len(words) + cols - 1) // cols
    list_h = rows * cfg["list_font_size"] * 1.55 + 40
    # grid as big as the page allows: full width, or the height left after title and word list
    cell = min(cw / (n + 0.5), (ch - 72 - list_h - 20) / (n + 0.5))
    grid_w = n * cell
    gx = x + (cw - grid_w) / 2
    gtop = y + ch - 72
    font = max(cfg["grid_font_size"], min(cell * 0.55, 30))
    draw_wordsearch_grid(c, ws, gx, gtop, cell, font)
    ly = gtop - grid_w - cell * 0.25 - 34
    col_w = cw / cols
    size = cfg["list_font_size"]
    c.setFont("Body", size)
    for i, w in enumerate(words):
        col, row = divmod(i, rows)
        wx, wy = x + col * col_w + 8, ly - row * size * 1.55
        c.rect(wx, wy - 1, size * 0.62, size * 0.62, stroke=1, fill=0)
        c.drawString(wx + size * 0.95, wy, w.upper())
    b.last_list_bottom = ly - (rows - 1) * size * 1.55
    b.next_page()


def wordsearch_answers(b, items):
    """items: list of (num, ws); 4 per page in a 2x2 layout."""
    for i in range(0, len(items), 4):
        x, y, cw, ch = b.box
        chunk = items[i:i + 4]
        slot_w, slot_h = cw / 2, (ch - 20) / 2
        for k, (num, ws) in enumerate(chunk):
            sx = x + (k % 2) * slot_w
            stop = y + ch - (k // 2) * slot_h
            n = len(ws["grid"])
            cell = min((slot_w - 30) / n, (slot_h - 50) / n)
            gx = sx + (slot_w - n * cell) / 2
            b.c.setFont("BodyBold", 13)
            b.c.drawCentredString(sx + slot_w / 2, stop - 14, f"Puzzle {num}")
            draw_wordsearch_grid(b.c, ws, gx, stop - 32, cell, cell * 0.62, answers=True)
        b.next_page()


# ---------- sudoku ----------

def draw_sudoku(c, grid, x0, y_top, size, font_size, given=None):
    cell = size / 9
    for i in range(10):
        lw = 2.4 if i % 3 == 0 else 0.7
        c.setLineWidth(lw)
        c.line(x0 + i * cell, y_top, x0 + i * cell, y_top - size)
        c.line(x0, y_top - i * cell, x0 + size, y_top - i * cell)
    for idx, v in enumerate(grid):
        if not v:
            continue
        r, col = divmod(idx, 9)
        is_given = given is None or given[idx]
        c.setFont("BodyBold" if is_given else "Body", font_size)
        c.setFillColorRGB(*(INK if is_given else GREY))
        c.drawCentredString(x0 + (col + 0.5) * cell, y_top - (r + 0.5) * cell - font_size * 0.35, str(v))
    c.setFillColorRGB(*INK)


def sudoku_pages(b, puzzles):
    per = b.cfg.get("per_page", 1)
    if b.framed and per == 1:
        for num, s in puzzles:
            ix, iy, iw, ih = design.framed_puzzle_header(b, num, f"Sudoku  \u00b7  {b.cfg['difficulty'].title()}",
                                                         icon=design.icon_of(b, s), i=num - 1)
            size = min(iw - 20, ih - 50)
            draw_sudoku(b.c, s["puzzle"], ix + (iw - size) / 2, iy + ih - 30 - (ih - 30 - size) / 2, size, size / 9 * 0.55)
            b.next_page()
        return
    for i in range(0, len(puzzles), per):
        x, y, cw, ch = b.box
        for k, (num, s) in enumerate(puzzles[i:i + per]):
            size = min(cw, 6.6 * inch) if per == 1 else min(cw * 0.75, (ch - 90) / 2)
            top = y + ch - 50 - k * (size + 60)
            b.c.setFont("BodyBold", 14)
            b.c.drawString(x, top + 18, f"PUZZLE {num}  ·  {b.cfg['difficulty'].upper()}")
            draw_sudoku(b.c, s["puzzle"], x + (cw - size) / 2, top, size, size / 9 * 0.55)
        b.next_page()


def sudoku_answers(b, puzzles):
    for i in range(0, len(puzzles), 6):
        x, y, cw, ch = b.box
        if b.framed:
            chunk = puzzles[i:i + 6]
            x, y, cw, ch = design.framed_puzzle_header(b, None, f"Answers  \u00b7  {chunk[0][0]}\u2013{chunk[-1][0]}")
            ch -= 20
        size = min((cw - 40) / 2, (ch - 120) / 3)
        for k, (num, s) in enumerate(puzzles[i:i + 6]):
            sx = x + (k % 2) * (cw / 2) + (cw / 2 - size) / 2
            top = y + ch - 30 - (k // 2) * (size + 40)
            b.c.setFont("BodyBold", 12)
            b.c.drawCentredString(sx + size / 2, top + 10, f"Puzzle {num}")
            given = [bool(v) for v in s["puzzle"]]
            draw_sudoku(b.c, s["solution"], sx, top, size, size / 9 * 0.55, given=given)
        b.next_page()


# ---------- maze ----------

def draw_maze(c, m, x0, y_top, cell, path=False, lw=2.0):
    rows, cols = m["rows"], m["cols"]
    c.setLineWidth(lw)
    c.setLineCap(1)
    for r in range(rows):
        for col in range(cols):
            o = m["open"][r][col]
            x, y = x0 + col * cell, y_top - r * cell
            if "N" not in o and not (r, col) == tuple(m["start"]):
                c.line(x, y, x + cell, y)
            if "W" not in o:
                c.line(x, y, x, y - cell)
            if r == rows - 1 and not (r, col) == tuple(m["end"]):
                c.line(x, y - cell, x + cell, y - cell)
            if col == cols - 1:
                c.line(x + cell, y, x + cell, y - cell)
    if path:
        c.setStrokeColorRGB(0.55, 0.55, 0.55)
        c.setLineWidth(max(lw * 1.2, cell * 0.16))
        pts = [(x0 + (cc + 0.5) * cell, y_top - (rr + 0.5) * cell) for rr, cc in m["path"]]
        p = c.beginPath()
        p.moveTo(*pts[0])
        for pt in pts[1:]:
            p.lineTo(*pt)
        c.drawPath(p, stroke=1, fill=0)
        c.setStrokeColorRGB(*INK)


def _arrow(c, x, y, s):
    """small downward triangle with its tip at (x, y - s)"""
    p = c.beginPath()
    p.moveTo(x - s, y)
    p.lineTo(x + s, y)
    p.lineTo(x, y - s * 1.3)
    p.close()
    c.drawPath(p, stroke=0, fill=1)


def maze_page(b, num, m):
    x, y, cw, ch = b.box
    if b.framed:
        x, y, cw, ch = design.framed_puzzle_header(b, num, f"Maze  \u00b7  {b.cfg['difficulty'].title()}", i=num - 1)
        ch -= 6
        y += 22
    else:
        b.c.setFont("BodyBold", 14)
        b.c.drawString(x, y + ch - 14, f"MAZE {num}")
    cell = min(cw / m["cols"], (ch - 80) / m["rows"])
    mx = x + (cw - cell * m["cols"]) / 2
    top = y + ch - 48
    b.c.setFont("Body", 12)
    b.c.drawString(mx + cell + 4, top + 6, "START")
    _arrow(b.c, mx + cell / 2, top + 12, 5)
    draw_maze(b.c, m, mx, top, cell)
    bottom = top - cell * m["rows"]
    _arrow(b.c, mx + cell * (m["cols"] - 0.5), bottom - 4, 5)
    b.c.drawRightString(mx + cell * (m["cols"] - 1) - 4, bottom - 16, "FINISH")
    b.next_page()


def maze_answers(b, items):
    for i in range(0, len(items), 4):
        x, y, cw, ch = b.box
        if b.framed:
            x, y, cw, ch = design.framed_puzzle_header(b, None, f"Answers  \u00b7  {items[i][0]}\u2013{items[min(i + 3, len(items) - 1)][0]}")
            ch -= 16
        slot_w, slot_h = cw / 2, (ch - 20) / 2
        for k, (num, m) in enumerate(items[i:i + 4]):
            cell = min((slot_w - 30) / m["cols"], (slot_h - 50) / m["rows"])
            sx = x + (k % 2) * slot_w + (slot_w - cell * m["cols"]) / 2
            top = y + ch - (k // 2) * slot_h - 32
            b.c.setFont("BodyBold", 12)
            b.c.drawCentredString(sx + cell * m["cols"] / 2, top + 12, f"Maze {num}")
            draw_maze(b.c, m, sx, top, cell, path=True, lw=1.0)
        b.next_page()


# ---------- main ----------

def generate(cfg, book_dir):
    rng = random.Random(f"{cfg['seed']}-{cfg['title']}")
    kind = cfg["puzzle_type"]
    out = []
    if kind == "wordsearch":
        entries = yaml.safe_load((book_dir / "content" / "puzzles.yaml").read_text(encoding="utf-8"))["puzzles"]
        if len(entries) < cfg["count"]:
            raise SystemExit(f"puzzles.yaml has {len(entries)} puzzles, book.yaml wants {cfg['count']}")
        for i, e in enumerate(entries[:cfg["count"]], 1):
            if len(e["words"]) != cfg["words_per_puzzle"]:
                raise SystemExit(f"puzzle {i} '{e['title']}' has {len(e['words'])} words, "
                                 f"expected {cfg['words_per_puzzle']}")
            level = e.get("difficulty", cfg["difficulty"])
            try:
                ws = make_wordsearch(e["words"], cfg["grid_size"], level, rng)
            except (ValueError, RuntimeError) as err:
                raise SystemExit(f"puzzle {i} '{e['title']}': {err}")
            out.append({"num": i, "title": e["title"], "difficulty": level, **ws})
    elif kind == "sudoku":
        for i in range(1, cfg["count"] + 1):
            out.append({"num": i, **make_sudoku(cfg["difficulty"], rng)})
    elif kind == "maze":
        for i in range(1, cfg["count"] + 1):
            out.append({"num": i, **make_maze(cfg["difficulty"], rng)})
    else:
        raise SystemExit(f"unknown puzzle_type {kind}")
    return out


def build(book_dir, dry_run=False):
    book_dir = Path(book_dir)
    cfg = yaml.safe_load((book_dir / "book.yaml").read_text(encoding="utf-8"))
    puzzles = generate(cfg, book_dir)
    print(f"generated {len(puzzles)} {cfg['puzzle_type']} puzzles")
    if dry_run:
        return
    dist = book_dir / "dist"
    dist.mkdir(exist_ok=True)
    (dist / "puzzles.json").write_text(json.dumps(puzzles), encoding="utf-8")

    b = Book(dist / "interior.pdf", cfg)
    f = b.framed
    # Difficulty stars only mean something when difficulty changes through the book
    # (per-puzzle `difficulty:` in puzzles.yaml). design.stars: auto (default) | show | hide
    levels = {"easy": 1, "medium": 2, "hard": 3}
    mode = (cfg.get("design") or {}).get("stars", "auto")
    varied = len({p.get("difficulty", cfg["difficulty"]) for p in puzzles}) > 1
    if mode == "show" or (mode == "auto" and varied):
        b.stars_for = {p["num"]: levels.get(p.get("difficulty", cfg["difficulty"]), 1) for p in puzzles}
    if kind_is_ws := cfg["puzzle_type"] == "wordsearch":
        # small worked example for the how-to page, from short words in puzzle 1
        short = sorted(puzzles[0]["words"], key=lambda w: len(w.replace(" ", "")))[:2]
        try:
            b.example = make_wordsearch(short, 7, "easy", random.Random("example"))
            b.draw_grid = draw_wordsearch_grid
        except (ValueError, RuntimeError):
            pass
    (design.title_page if f else title_page)(b)
    copyright_page(b)
    (design.how_to_page if f else how_to_page)(b)
    d = cfg.get("design") or {}
    if f and d.get("tracker"):
        design.tracker_page(b, len(puzzles))
    section = design.section_page if f else section_page
    if b.page % 2 == 0:  # start puzzles on a right-hand page
        b.next_page()
    b.numbered = True
    kind = cfg["puzzle_type"]
    if kind == "wordsearch":
        entries = {e["title"]: e for e in yaml.safe_load(
            (book_dir / "content" / "puzzles.yaml").read_text(encoding="utf-8"))["puzzles"]}
        for p in puzzles:
            if f:
                design.wordsearch_page(b, p["num"], {**entries.get(p["title"], {}), **p}, p, draw_wordsearch_grid)
            else:
                wordsearch_page(b, p["num"], p, p)
        if b.page % 2 == 0:
            b.next_page()
        section(b, "Answers")
        items = [(p["num"], p) for p in puzzles]
        design.wordsearch_answers(b, items, draw_wordsearch_grid) if f else wordsearch_answers(b, items)
    elif kind == "sudoku":
        sudoku_pages(b, [(p["num"], p) for p in puzzles])
        section(b, "Answers")
        sudoku_answers(b, [(p["num"], p) for p in puzzles])
    else:
        for p in puzzles:
            maze_page(b, p["num"], p)
        section(b, "Answers")
        maze_answers(b, [(p["num"], p) for p in puzzles])
    (design.back_page if f else back_page)(b)
    if f and d.get("certificate"):
        design.certificate_page(b)
    if f and d.get("bonus_url"):
        design.bonus_page(b, d["bonus_url"])
    # KDP: even page count, at least 24. Filler pages stay truly blank (no page number).
    b.numbered = False
    while b.page - 1 < 24 or (b.page - 1) % 2:
        b.next_page()
    pages = b.page - 1
    b.save()
    (dist / "layout.json").write_text(json.dumps(getattr(b, "layout_issues", []), indent=2), encoding="utf-8")
    info = {"pages": pages, "trim": cfg["trim"], "paper": cfg.get("paper", "white"),
            "puzzle_type": kind, "count": len(puzzles)}
    (dist / "build.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
    print(f"wrote {dist / 'interior.pdf'} ({pages} pages)")


